<h1 align=center><strong>Additional Information</strong></h1>
<p>
This eligibility criteria ensures that candidates with the appropriate academic background and interest in business management can apply for the BBA program at Mewar Institute of Management.
</p>
<ul style=circle>
<li>
<h3 style=color:red><strong>Who Can Apply?</strong></h3>
</li>
</ul>
<ul style=black>
<li>
Who have completed their 10+2 education in any stream, obtaining at least 45% marks for General and OBC categories, and a minimum of 40% marks for SC and ST categories.
</li>
<h4 align=center><strong>OR</strong></h4>
<li>
Who have appeared for the 10+2 examinations and are currently awaiting their results are permitted to submit an application. Nonetheless, their application will be deemed valid only if they achieve a passing score in the qualifying examination.
</li>
</ul>
<ul style=circle>
<li>
<h3 style=color:red><strong>How to Apply?</strong></h3>
</li>
</ul>
<ul style=black>
<li>
Candidates who wish to apply may collect application forms from the Admission Office at Mewar Institute of Management, Ghaziabad, or alternatively, they can complete the Online Inquiry form by following the provided link.
</li>
<li>
Individuals interested in the BBA program must schedule a meeting with the Admission Counsellor on the Institute's premises.
Selection Process
</li>
<li>
Admission will be granted based on the outcome of a personal interview and the applicant's merit.
</li>
</ul>
<h3><strong>Note:</strong></h3>
<h4>Candidates who have a gap of one or two years following the completion of their 10+2 education must provide a Gap Year Certificate.<h4>
