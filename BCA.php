<h2 style=color:rgb(255,0,0)><strong><ul type="black"><li>About this Course</li></ul></strong></h2>
<p>
The Bachelor of Computer Applications (BCA) at the Mewar Institute of Management in Ghaziabad is <strong>a three-year, full-time undergraduate program affiliated with Chaudhary Charan Singh University (CCSU), Meerut.</strong> The course is designed to provide a strong foundation in computer science and software development, preparing students for the dynamic IT industry. 
</p>
<h2 style=color:red rgb(0, 0, 0)>Course Overview & Curriculum</h2>
<ul type=circle>
<li>
<strong>Duration:</strong> 3 years (divided into 6 semesters).
</li>
<li>
<strong>Core Subjects: </strong>The curriculum includes programming languages (C, C++), data structures, software engineering, computer networks, artificial intelligence, and web development.
</li>
<li>
<strong>Specializations:</strong> Focused primarily on Computer Applications.
</li>
<li>                                                                                                                                                                                                                                                                                      
<strong>Value-Added Courses (VAC):</strong> The institute offers short, industry-focused modules to enhance technical proficiency and soft skills.
</li>
<br>
<br>
<h2 style:color=red>Placement & Career Support</h2>
<ul style=square>
<li>
<strong>Placement Cell:</strong> A dedicated cell assists students with resume building, mock interviews, and connecting with recruiters.
</li>
<li>
<strong>Notable Recruiters:</strong> Companies like Amazon, TCS, Tech Mahindra, and Capgemini have participated in campus recruitment.
</li>
<li>
<strong>Salary Packages: </strong>Recent reports indicate a median package of around ₹2.40 LPA, with the highest packages reaching up to ₹3 LPA.
</li>
<li>
<strong>Internships:</strong> Compulsory 6 to 8-week summer internships are part of the curriculum to provide hands-on experience.
</li>
</ul>



