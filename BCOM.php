<h2 style=color:black><strong><ul type="black"><li>About this Course</li></ul></strong></h2>
<p>
Mewar University offers a <strong>3-year Bachelor of Commerce (B.Com/B.Com Hons.) program, focusing on accounting, finance, taxation, and business law</strong>, often designed with comprehensive, industry-relevant curriculum, including options affiliated with <u>Ch. Charan Singh University</u> (CCS University) or through the main Mewar University campus. Total tuition fees for the B.Com program are approximately INR 90,000, with fees at the affiliated <u>Mewar Institute of Management</u> around INR 40,000 per annum. 
</p>
<h2 style=color:green align=center>Key Details for B.Com at Mewar University:</h2>
<ul style=circle>
<li>
<strong>Program Structure: </strong>The B.Com program is a 3-year undergraduate degree designed to provide in-depth knowledge in subjects like accounting, management, business law, and taxation.
</li>
<li>
<strong>Affiliation/Recognition:</strong> The university is recognized by the UGC and is a member of the Association of Indian Universities (AIU). Some courses are affiliated with CCS University, Meerut.
</li>
<li>
<strong>Admission Process:</strong> Admission is based on the Mewar University Entrance Exam (MUEE) or valid scores in the Common University Entrance Test (CUET).
</li>
<li>
<strong>Scholarships:</strong> Mewar University offers scholarships for meritorious students, including up to 75% tuition fee exemption for top scorers and specific exemptions for students with over 85-90% in 10+2.
</li>
<li>
<strong>Curriculum:</strong> The curriculum is regularly updated to meet industry trends and offers a blend of theoretical and practical knowledge. 
</li>
</ul>
<h2><strong>Fee Structure (Approximate):</strong></h2>
<ul style=black>
<li>
<strong>Mewar University Main Campus:</strong> Total tuition fee for B.Com (Hons.) is around INR 90,000.
</li>
<li>
<strong>Mewar Institute of Management (Affiliated):</strong> Approximately INR 40,000 per annum. 
</li>
</ul>
